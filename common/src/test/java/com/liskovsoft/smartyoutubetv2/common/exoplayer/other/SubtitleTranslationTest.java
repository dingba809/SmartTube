package com.liskovsoft.smartyoutubetv2.common.exoplayer.other;

import com.liskovsoft.mediaserviceinterfaces.data.MediaSubtitle;

import org.junit.Test;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.List;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertNull;
import static org.junit.Assert.assertTrue;

/**
 * Plain JUnit on purpose. Robolectric 4.6.1 cannot run on the JDK 17 CI runner: its ASM
 * version chokes on the class files. So only code that touches no Android API is covered
 * here: URL normalization, answer sanitizing, the cache, the cue structure the parser reads
 * out of a file and the deduplicator both sides of the prefetcher rely on.
 */
public class SubtitleTranslationTest {
    private static final String VTT = "WEBVTT\n"
            + "Kind: captions\n"
            + "Language: en\n"
            + "\n"
            + "00:00:00.080 --> 00:00:02.230\n"
            + "Hello, world!\n"
            + "\n"
            + "00:00:02.230 --> 00:00:04.500\n"
            + "This is a test.\n"
            + "\n"
            + "00:00:04.500 --> 00:00:07.000\n"
            + "<c>Don't</c> forget to subscribe.\n";

    /** Autogenerated captions repeat the previous line in every cue: the scrolling window. */
    private static final String ROLLING_VTT = "WEBVTT\n"
            + "Kind: captions\n"
            + "Language: en\n"
            + "\n"
            + "00:00:00.080 --> 00:00:02.230\n"
            + "Hello, world!\n"
            + "\n"
            + "00:00:02.230 --> 00:00:04.500\n"
            + "Hello, world!\n"
            + "This is a test.\n"
            + "\n"
            + "00:00:04.500 --> 00:00:07.000\n"
            + "This is a test.\n"
            + "Goodbye!\n";

    @Test
    public void buildEndpointAcceptsHostV1AndFullEndpoint() {
        assertEquals("https://api.deepseek.com/v1/chat/completions",
                SubtitleTranslator.buildEndpoint("https://api.deepseek.com"));
        assertEquals("https://api.deepseek.com/v1/chat/completions",
                SubtitleTranslator.buildEndpoint("https://api.deepseek.com/"));
        assertEquals("https://api.deepseek.com/v1/chat/completions",
                SubtitleTranslator.buildEndpoint("https://api.deepseek.com/v1"));
        assertEquals("https://api.deepseek.com/v1/chat/completions",
                SubtitleTranslator.buildEndpoint("https://api.deepseek.com/v1/chat/completions"));
    }

    @Test
    public void sanitizeStripsQuotesAndCodeFence() {
        assertEquals("你好", SubtitleTranslator.sanitize("  你好  "));
        assertEquals("你好", SubtitleTranslator.sanitize("\"你好\""));
        assertEquals("你好", SubtitleTranslator.sanitize("```\n你好\n```"));
    }

    @Test
    public void sanitizeRejectsEmpty() {
        assertNull(SubtitleTranslator.sanitize(null));
        assertNull(SubtitleTranslator.sanitize(""));
        assertNull(SubtitleTranslator.sanitize("   "));
    }

    @Test
    public void cacheKeepsTranslationUntilCleared() {
        SubtitleTranslationCache cache = new SubtitleTranslationCache();

        assertNull(cache.get("hello"));
        cache.put("hello", "你好");
        assertEquals("你好", cache.get("hello"));

        cache.clear();
        assertNull(cache.get("hello"));
    }

    @Test
    public void cacheIgnoresNullsAndEvictsOldest() {
        SubtitleTranslationCache cache = new SubtitleTranslationCache();

        cache.put(null, "x");
        cache.put("x", null);
        assertNull(cache.get(null));
        assertNull(cache.get("x"));

        for (int i = 0; i < 2000; i++) {
            cache.put("line " + i, "译 " + i);
        }

        assertEquals("译 1999", cache.get("line 1999"));
        assertNull(cache.get("line 0"));
    }

    @Test
    public void extractCuesSkipsHeaderAndTrimsLines() {
        // Tags are left in place here: decoding them is Html.fromHtml's job, exactly as in
        // ExoPlayer, and that call cannot run on the JVM.
        assertEquals(
                Arrays.asList("Hello, world!", "This is a test.", "<c>Don't</c> forget to subscribe."),
                SubtitleVttParser.extractCues(VTT));
    }

    @Test
    public void extractCuesHandlesGarbage() {
        assertTrue(SubtitleVttParser.extractCues(null).isEmpty());
        assertTrue(SubtitleVttParser.extractCues("").isEmpty());
        assertTrue(SubtitleVttParser.extractCues("WEBVTT\n\n").isEmpty());
    }

    /**
     * The whole prefetcher rests on this: the cue structure read out of the file must be exactly
     * the one ExoPlayer hands over at playback time, or the derived cache keys differ and the
     * translations never hit.
     */
    @Test
    public void extractedCuesMatchTheLiveCueSequence() {
        assertEquals(
                Arrays.asList("Hello, world!", "Hello, world!\nThis is a test.", "This is a test.\nGoodbye!"),
                SubtitleVttParser.extractCues(ROLLING_VTT));
    }

    @Test
    public void deduplicatorStripsRollingWindowRepeats() {
        SubtitleTextDeduplicator deduplicator = new SubtitleTextDeduplicator();

        assertEquals("Hello, world!", deduplicator.deduplicate("Hello, world!"));
        assertEquals("This is a test.", deduplicator.deduplicate("Hello, world!\nThis is a test."));
        assertEquals("Goodbye!", deduplicator.deduplicate("This is a test.\nGoodbye!"));
    }

    @Test
    public void deduplicatorSkipsTrailingEmptyCues() {
        SubtitleTextDeduplicator deduplicator = new SubtitleTextDeduplicator();

        assertNull(deduplicator.deduplicate("Hello\n"));
        assertEquals("Hello", deduplicator.deduplicate("Hello"));
    }

    /** Both sides must derive the same keys from the same cue sequence. */
    @Test
    public void bothSidesDeriveTheSameKeys() {
        List<String> fromFile = dedupe(SubtitleVttParser.extractCues(ROLLING_VTT));
        List<String> fromPlayer = dedupe(Arrays.asList(
                "Hello, world!", "Hello, world!\nThis is a test.", "This is a test.\nGoodbye!"));

        assertEquals(Arrays.asList("Hello, world!", "This is a test.", "Goodbye!"), fromFile);
        assertEquals(fromFile, fromPlayer);
    }

    private static List<String> dedupe(List<String> cues) {
        SubtitleTextDeduplicator deduplicator = new SubtitleTextDeduplicator();
        List<String> result = new ArrayList<>();

        for (String cue : cues) {
            String text = deduplicator.deduplicate(cue);

            if (text != null) {
                result.add(text);
            }
        }

        return result;
    }

    @Test
    public void parseBatchReadsNumberedLines() {
        assertEquals(Arrays.asList("你好", "世界"),
                SubtitleTranslator.parseBatch("[1] 你好\n[2] 世界", 2));
    }

    @Test
    public void parseBatchToleratesCodeFenceAndMissingLines() {
        assertEquals(Arrays.asList("你好", null),
                SubtitleTranslator.parseBatch("```\n[1] 你好\n```", 2));
        // Out of range numbers are ignored instead of crashing.
        assertEquals(Arrays.asList("你好", null),
                SubtitleTranslator.parseBatch("[1] 你好\n[9] 越界", 2));
        assertNull(SubtitleTranslator.parseBatch(null, 2).get(0));
    }

    @Test
    public void batchMessageNumbersEachLineAndFlattensMultilineCues() {
        String message = SubtitleTranslator.buildBatchUserMessage(Arrays.asList("one", "two\nlines"));

        assertEquals("[1] one\n[2] two lines", message);
    }

    // ---- subtitle track preference ----

    @Test
    public void preferencePicksChineseAsIs() {
        SubtitleTrackPreference.Pick pick = SubtitleTrackPreference.pick(Arrays.asList(
                subtitle(".en", "en", null), subtitle(".zh-Hans", "zh-Hans", null)));

        assertEquals(".zh-Hans", pick.vssId);
        assertFalse(pick.translate);
    }

    @Test
    public void preferencePicksEnglishForTranslation() {
        SubtitleTrackPreference.Pick pick = SubtitleTrackPreference.pick(Arrays.asList(
                subtitle(".ja", "ja", null), subtitle(".en", "en", null)));

        assertEquals(".en", pick.vssId);
        assertTrue(pick.translate);
    }

    @Test
    public void preferenceFallsBackToAutogeneratedEnglish() {
        SubtitleTrackPreference.Pick pick = SubtitleTrackPreference.pick(Arrays.asList(
                subtitle(".ja", "ja", null), subtitle(".en", "en", "asr")));

        assertEquals(".en", pick.vssId);
        assertTrue(pick.translate);
    }

    @Test
    public void preferencePrefersHumanMadeOverAutogenerated() {
        SubtitleTrackPreference.Pick pick = SubtitleTrackPreference.pick(Arrays.asList(
                subtitle(".zh-Hans.asr", "zh-Hans", "asr"), subtitle(".zh-Hant", "zh-Hant", null)));

        assertEquals(".zh-Hant", pick.vssId);
        assertFalse(pick.translate);
    }

    @Test
    public void preferenceAcceptsAutogeneratedChinese() {
        SubtitleTrackPreference.Pick pick = SubtitleTrackPreference.pick(Arrays.asList(
                subtitle(".en", "en", null), subtitle(".zh-Hans", "zh-Hans", "asr")));

        assertEquals(".zh-Hans", pick.vssId);
        assertFalse(pick.translate);
    }

    @Test
    public void preferenceGivesUpOnOtherLanguages() {
        assertNull(SubtitleTrackPreference.pick(Arrays.asList(subtitle(".ja", "ja", null))));
        assertNull(SubtitleTrackPreference.pick(Collections.emptyList()));
        assertNull(SubtitleTrackPreference.pick(null));
    }

    private static MediaSubtitle subtitle(String vssId, String languageCode, String kind) {
        return new MediaSubtitle() {
            @Override
            public String getBaseUrl() {
                return null;
            }

            @Override
            public boolean isTranslatable() {
                return false;
            }

            @Override
            public String getLanguageCode() {
                return languageCode;
            }

            @Override
            public String getVssId() {
                return vssId;
            }

            @Override
            public String getName() {
                return null;
            }

            @Override
            public String getMimeType() {
                return null;
            }

            @Override
            public String getCodecs() {
                return null;
            }

            @Override
            public String getType() {
                return kind;
            }
        };
    }
}
