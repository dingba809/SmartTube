package com.liskovsoft.smartyoutubetv2.common.exoplayer.other;

import com.liskovsoft.mediaserviceinterfaces.data.MediaSubtitle;

import java.util.List;

/**
 * Decides which track to fall back on when captions are switched on and there is no remembered
 * choice: a Chinese track is used as is, otherwise an English one is used as the source for the
 * AI translation.<br/>
 * Matches on the YouTube language code rather than the displayed name, since the name is
 * localized ("英语（自动生成）" on a Chinese device) and would need matching per locale.
 */
public class SubtitleTrackPreference {
    private static final String CHINESE = "zh";
    private static final String ENGLISH = "en";
    /** YouTube marks speech recognition tracks with this kind. */
    private static final String KIND_ASR = "asr";

    public static class Pick {
        public final String vssId;
        /** True when the line has to be translated, i.e. the track is not in the wanted language. */
        public final boolean translate;

        public Pick(String vssId, boolean translate) {
            this.vssId = vssId;
            this.translate = translate;
        }
    }

    public static Pick pick(List<MediaSubtitle> subtitles) {
        if (subtitles == null || subtitles.isEmpty()) {
            return null;
        }

        MediaSubtitle chinese = firstByLanguage(subtitles, CHINESE, false); // human made first
        if (chinese == null) {
            chinese = firstByLanguage(subtitles, CHINESE, true);
        }
        if (chinese != null) {
            return new Pick(chinese.getVssId(), false);
        }

        MediaSubtitle english = firstByLanguage(subtitles, ENGLISH, false); // human made first
        if (english == null) {
            english = firstByLanguage(subtitles, ENGLISH, true);
        }
        if (english != null) {
            return new Pick(english.getVssId(), true);
        }

        return null;
    }

    private static MediaSubtitle firstByLanguage(List<MediaSubtitle> subtitles, String prefix, boolean autoGenerated) {
        for (MediaSubtitle subtitle : subtitles) {
            String code = subtitle.getLanguageCode();

            if (code != null && code.toLowerCase().startsWith(prefix)
                    && isAutoGenerated(subtitle) == autoGenerated) {
                return subtitle;
            }
        }

        return null;
    }

    private static boolean isAutoGenerated(MediaSubtitle subtitle) {
        return KIND_ASR.equals(subtitle.getType());
    }
}
