package com.liskovsoft.smartyoutubetv2.common.exoplayer.other;

import com.liskovsoft.mediaserviceinterfaces.data.MediaSubtitle;

import java.util.List;
import java.util.Locale;

/** Language policy for the actual selectable tracks, including tracks sharing a vssId. */
public class SubtitleTrackPreference {
    public static class Track {
        public final String vssId;
        public final String languageCode;
        public final boolean autoGenerated;

        public Track(String vssId, String languageCode, boolean autoGenerated) {
            this.vssId = vssId;
            this.languageCode = languageCode;
            this.autoGenerated = autoGenerated;
        }
    }

    public static class Pick {
        public final String vssId;
        public final boolean translate;
        public final int index;

        private Pick(Track track, int index) {
            vssId = track.vssId;
            translate = shouldTranslate(track.languageCode);
            this.index = index;
        }
    }

    public static String languageCodeOf(String vssId) {
        if (vssId == null) {
            return null;
        }
        // YouTube uses both .en (manual) and a.en (speech recognition).
        String[] parts = vssId.split("\\.");
        return parts.length >= 2 && (parts[0].isEmpty() || "a".equals(parts[0]))
                && !parts[1].isEmpty() ? parts[1] : null;
    }

    public static boolean shouldTranslate(String languageCode) {
        return languageCode != null && !isLanguage(languageCode, "zh");
    }

    public static Pick pick(List<Track> tracks) {
        if (tracks == null) {
            return null;
        }
        // Only the regular category's Chinese is automatic; autogenerated Chinese must not
        // preempt the English source requested by the user.
        for (int priority = 0; priority < 3; priority++) {
            for (int i = 0; i < tracks.size(); i++) {
                Track track = tracks.get(i);
                boolean matches = priority == 0
                        ? !track.autoGenerated && isLanguage(track.languageCode, "zh")
                        : isLanguage(track.languageCode, "en") && track.autoGenerated == (priority == 2);
                if (matches) {
                    return new Pick(track, i);
                }
            }
        }
        return null;
    }

    private static boolean isLanguage(String code, String language) {
        if (code == null) {
            return false;
        }
        String normalized = code.toLowerCase(Locale.ROOT).replace('_', '-');
        return normalized.equals(language) || normalized.startsWith(language + "-");
    }

    /** Names use the same normalization as ExoPlayer's Format.language before matching. */
    public static MediaSubtitle findSubtitle(List<MediaSubtitle> subtitles, String vssId, String name) {
        if (subtitles == null || vssId == null) {
            return null;
        }
        MediaSubtitle onlyMatch = null;
        int matches = 0;
        for (MediaSubtitle subtitle : subtitles) {
            if (!vssId.equals(subtitle.getVssId())) {
                continue;
            }
            String subtitleName = subtitle.getName() != null ? subtitle.getName() : subtitle.getLanguageCode();
            if (name != null && normalizeName(name).equals(normalizeName(subtitleName))) {
                return subtitle;
            }
            onlyMatch = subtitle;
            matches++;
        }
        // Never guess among YouTube translations that share their source track's ID.
        return matches == 1 ? onlyMatch : null;
    }

    private static String normalizeName(String name) {
        return name == null ? null : name.replace('_', '-').toLowerCase(Locale.ROOT);
    }
}
