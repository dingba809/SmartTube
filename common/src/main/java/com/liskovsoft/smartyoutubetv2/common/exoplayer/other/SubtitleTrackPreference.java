package com.liskovsoft.smartyoutubetv2.common.exoplayer.other;

import java.util.List;

/**
 * Decides which track to fall back on when captions are switched on and there is no remembered
 * choice: a Chinese track is used as is, otherwise an English one is used as the source for the
 * AI translation.<br/>
 * Works off the tracks ExoPlayer actually offers rather than the format info payload, since the
 * latter turned out not to carry every language. The language code is read out of the vssId
 * (".en.nP7-2PuUl7o" to "en") instead of the display name, which is localized.
 */
public class SubtitleTrackPreference {
    private static final String CHINESE = "zh";
    private static final String ENGLISH = "en";

    /** One selectable subtitle track. */
    public static class Track {
        public final String vssId;
        public final String languageCode;
        /** True for speech recognition tracks as well as machine translated ones. */
        public final boolean autoGenerated;

        public Track(String vssId, String languageCode, boolean autoGenerated) {
            this.vssId = vssId;
            this.languageCode = languageCode;
            this.autoGenerated = autoGenerated;
        }
    }

    public static class Pick {
        public final String vssId;
        /** True when the line has to be translated, i.e. the track is not in the wanted language. */
        public final boolean translate;

        public Pick(String vssId, boolean translate) {
            this.vssId = vssId;
            this.translate = translate;
        }
    }

    /**
     * {@code .en.nP7-2PuUl7o} becomes {@code en}, {@code .zh-Hans.abc} becomes {@code zh-Hans}.
     */
    public static String languageCodeOf(String vssId) {
        if (vssId == null) {
            return null;
        }

        String[] parts = vssId.split("\\.");

        return parts.length >= 2 && !parts[1].isEmpty() ? parts[1] : null;
    }

    public static Pick pick(List<Track> tracks) {
        if (tracks == null || tracks.isEmpty()) {
            return null;
        }

        Track chinese = firstByLanguage(tracks, CHINESE, false); // human made first
        if (chinese == null) {
            chinese = firstByLanguage(tracks, CHINESE, true);
        }
        if (chinese != null) {
            return new Pick(chinese.vssId, false);
        }

        Track english = firstByLanguage(tracks, ENGLISH, false); // human made first
        if (english == null) {
            english = firstByLanguage(tracks, ENGLISH, true);
        }
        if (english != null) {
            return new Pick(english.vssId, true);
        }

        return null;
    }

    private static Track firstByLanguage(List<Track> tracks, String prefix, boolean autoGenerated) {
        for (Track track : tracks) {
            if (track.languageCode != null && track.languageCode.toLowerCase().startsWith(prefix)
                    && track.autoGenerated == autoGenerated) {
                return track;
            }
        }

        return null;
    }
}
